import 'dart:async';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:streamline_iptv/data/speed_test.dart';

class Headers implements HttpHeaders {
  final values = <String, Object>{};
  @override
  void set(String name, Object value, {bool preserveHeaderCase = false}) {
    values[name] = value;
  }

  @override
  set contentType(ContentType? value) {
    values['content-type'] = value.toString();
  }

  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

class Response extends Stream<List<int>> implements HttpClientResponse {
  Response(this.body, this.statusCode);
  final Stream<List<int>> body;
  @override
  final int statusCode;
  @override
  StreamSubscription<List<int>> listen(
    void Function(List<int>)? onData, {
    Function? onError,
    void Function()? onDone,
    bool? cancelOnError,
  }) => body.listen(
    onData,
    onError: onError,
    onDone: onDone,
    cancelOnError: cancelOnError,
  );
  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

class Request implements HttpClientRequest {
  Request(this.response);
  final Response response;
  @override
  final Headers headers = Headers();
  @override
  bool followRedirects = true;
  @override
  int contentLength = -1;
  int sent = 0;
  bool aborted = false;
  @override
  void add(List<int> data) {
    sent += data.length;
  }

  @override
  Future<void> flush() async {}
  @override
  Future<HttpClientResponse> close() async => response;
  @override
  Future<HttpClientResponse> get done async => response;
  @override
  void abort([Object? exception, StackTrace? stackTrace]) {
    aborted = true;
  }

  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

class Client implements HttpClient {
  final calls = <({String method, Uri uri, Request request})>[];
  int status = 200;
  int extraBytes = 0;
  Object? failure;
  bool closed = false;
  StreamController<List<int>>? stalledBody;
  @override
  set connectionTimeout(Duration? value) {}
  @override
  set autoUncompress(bool value) {}
  @override
  Future<HttpClientRequest> openUrl(String method, Uri url) async {
    if (failure != null) throw failure!;
    final bytes = method == 'GET'
        ? int.parse(url.queryParameters['bytes']!) + extraBytes
        : 0;
    final request = Request(
      Response(
        stalledBody?.stream ?? Stream.value(List<int>.filled(bytes, 0)),
        status,
      ),
    );
    calls.add((method: method, uri: url, request: request));
    return request;
  }

  @override
  void close({bool force = false}) {
    closed = true;
    final controller = stalledBody;
    if (controller != null && !controller.isClosed) {
      unawaited(controller.close());
    }
  }

  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

void main() {
  test(
    'speed traffic uses fixed HTTPS endpoints, bypasses caches and uploads only generated bytes',
    () async {
      final client = Client();
      await HttpOverrides.runZoned(() async {
        final transport = IoSpeedTestTransport();
        await transport.measure(bytes: 1024);
        await transport.measure(bytes: 100003, upload: true);
        expect(client.calls.map((c) => c.uri.host).toSet(), {
          'speed.cloudflare.com',
        });
        expect(
          client.calls.every(
            (c) =>
                c.uri.scheme == 'https' &&
                !c.uri.queryParameters.containsKey('password'),
          ),
          true,
        );
        expect(client.calls.map((c) => c.uri.path), ['/__down', '/__up']);
        expect(client.calls.every((c) => !c.request.followRedirects), true);
        expect(
          client.calls.first.request.headers.values['cache-control'],
          'no-store',
        );
        expect(client.calls.last.request.sent, 100003);
        expect(client.calls.last.request.contentLength, 100003);
        transport.close();
        expect(client.closed, true);
      }, createHttpClient: (_) => client);
    },
  );
  for (final status in [302, 403, 503]) {
    test(
      'HTTP $status fails without following redirects or treating it as speed data',
      () async {
        final client = Client()..status = status;
        await HttpOverrides.runZoned(() async {
          final transport = IoSpeedTestTransport();
          await expectLater(
            transport.measure(bytes: 1024),
            throwsA(
              isA<SpeedTestFailure>().having((e) => e.code, 'code', 'http'),
            ),
          );
          expect(client.calls.length, 1);
          expect(client.closed, true);
          transport.close();
        }, createHttpClient: (_) => client);
      },
    );
  }
  for (final extra in [-1, 1024]) {
    test(
      'truncated and oversized bodies fail instead of producing false bandwidth: $extra',
      () async {
        final client = Client()..extraBytes = extra;
        await HttpOverrides.runZoned(() async {
          final transport = IoSpeedTestTransport();
          await expectLater(
            transport.measure(bytes: 1024),
            throwsA(
              isA<SpeedTestFailure>().having((e) => e.code, 'code', 'response'),
            ),
          );
          expect(client.closed, true);
          transport.close();
        }, createHttpClient: (_) => client);
      },
    );
  }
  test(
    'response-body timeout force-closes the client and retains no native error text',
    () async {
      final client = Client()..stalledBody = StreamController<List<int>>();
      await HttpOverrides.runZoned(() async {
        final transport = IoSpeedTestTransport(
          timeout: const Duration(milliseconds: 20),
        );
        await expectLater(
          transport.measure(bytes: 1024),
          throwsA(
            isA<SpeedTestFailure>().having((e) => e.code, 'code', 'timeout'),
          ),
        );
        expect(client.closed, true);
        transport.close();
      }, createHttpClient: (_) => client);
    },
  );
}
